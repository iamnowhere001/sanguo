/**
 * 地理配表（S 档 · 地形化）
 *
 * 这里是**唯一的地理真值源**：经纬度 → 世界坐标的投影、海岸线、河流、湖泊、
 * 山脉、荒漠、林地、沼泽，以及 61 座城的真实落位。
 *
 * 设计裁决见 `docs/全地图规格-v1.md`，三条约束写在最前面：
 *
 * 1. **本文件只描述地理，不参与任何规则**。
 *    `neighborsOf()` 仍然查 `scenarios.ts` 的邻接表 —— S 档不动玩法，
 *    地形只是"让地图看起来像中国"，不是"让行军按地形算代价"（那是 M 档）。
 * 2. **所有控制点用经纬度写**，投影集中在一个纯函数里。
 *    这样换地图尺寸 / 换投影只改常量，不用重标 200 个点。
 * 3. **不得手绘栅格**。96×72 = 6,912 格手涂无法维护，这里只给 ~250 个
 *    地理控制点，栅格由 `render/terrainGrid.ts` 确定性生成。
 *
 * 坐标口径：经度 99.0–124.5°E，纬度 20.5–42.5°N，等距圆柱投影。
 * 该区间在中纬度（约 32°N）的横纵比例约 1.15，与真实 1/cos(32°) ≈ 1.18 接近，
 * 因此不需要额外做墨卡托校正，城池相对位置不会明显变形。
 */

/**
 * 世界栅格尺寸：576 列 × 432 行，每格 12 世界单位。
 *
 * 在 192×144 基础上长宽再各 ×3：格数 82,944 提升到 248,832（9 倍面积），
 * 世界尺寸 2304×1728 → 6912×5184。经纬窗口保持不变，城池仍按真实经纬度
 * 落位，但城与城之间终于有足够的行军纵深；长江、黄河与洞庭 / 鄱阳
 * 也各自展开成 12–18 格宽的江面 / 湖面，可以直接在整张大地图上打水战。
 *
 * 渲染层用「总览 100% + 默认 200%」的相机适配更大世界：
 * 100% 看天下大势，200% 时城池与世界物件的屏幕尺寸与旧版 100% 一致。
 */
export const MAP = {
  cols: 576,
  rows: 432,
  tile: 12,
  /** 世界坐标宽高（= cols × tile / rows × tile） */
  get width(): number {
    return this.cols * this.tile;
  },
  get height(): number {
    return this.rows * this.tile;
  },
} as const;

/**
 * 大地图数据版本。存档没有这个字段时，按旧版 96×72 迁移坐标。
 * 以后若继续扩容，递增此值并在 `save/migrate.ts` 增加对应缩放。
 */
export const MAP_VERSION = 3;

export const LON_RANGE: [number, number] = [99.0, 124.5];
export const LAT_RANGE: [number, number] = [20.5, 42.5];

export type Pt = [lon: number, lat: number];

/** 经纬度 → 世界坐标（左上角原点，y 向下） */
export function projectLonLat(lon: number, lat: number): { x: number; y: number } {
  const [lon0, lon1] = LON_RANGE;
  const [lat0, lat1] = LAT_RANGE;
  return {
    x: ((lon - lon0) / (lon1 - lon0)) * MAP.width,
    y: ((lat1 - lat) / (lat1 - lat0)) * MAP.height,
  };
}

/** 经纬度 → 栅格列行（未取整，可越界） */
export function lonLatToTile(lon: number, lat: number): { col: number; row: number } {
  const [lon0, lon1] = LON_RANGE;
  const [lat0, lat1] = LAT_RANGE;
  return {
    col: ((lon - lon0) / (lon1 - lon0)) * MAP.cols,
    row: ((lat1 - lat) / (lat1 - lat0)) * MAP.rows,
  };
}

