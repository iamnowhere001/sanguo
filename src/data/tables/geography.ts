export interface RiverDef {
  id: string;
  name: string;
  /** 上游 → 下游 */
  points: Pt[];
  /** 相对宽度（黄河 / 长江 用 1，支流 0.6） */
  scale: number;
}

/**
 * 河流半宽（度）。干流 scale=1 → 0.18°，支流 scale=0.55 → 0.14°。
 * 在 576×432 格网下，经向每格约 0.0443°，因此干流江面约 8 格、支流约 6–7 格；
 * 既保留水军展开与渡口空间，又不再让一条支流在近景里吞掉半屏。
 */
export function riverHalfWidth(scale: number): number {
  return 0.09 + scale * 0.09;
}

/** 河流在屏幕上的世界宽度（与不可通行河岸带对齐，略留滩涂） */
export function riverWorldWidth(scale: number): number {
  const unitsPerLon = MAP.width / (LON_RANGE[1] - LON_RANGE[0]);
  return riverHalfWidth(scale) * 2 * unitsPerLon * 0.92;
}

